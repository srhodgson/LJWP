package Chapter03;

public class ArithOps {
    public static void main(String[] args) {
        int res = 3 + 2 * 4;
        System.out.println(res); // 11

        res = (3 + 2) * 4;
        System.out.println(res); // 20

        res = 6 + 4 - 2;
        System.out.println(res); // 8

        res = 10 / 4 * 6 % 10;
        System.out.println(res); // 2
    }
}

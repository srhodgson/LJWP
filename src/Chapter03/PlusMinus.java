package Chapter03;

public class PlusMinus {
    public static void main(String[] args) {
        int x = +6;
        int y = -x;
        System.out.println(x); // 6
        System.out.println(y); // -6

        int z = (int)3.45;
        System.out.println(z); // 3

        boolean b = true;
        System.out.println(!b); // false
        System.out.println(b);  // true
    }
}
